#!/usr/bin/env python3
"""gen_syms.py OUT.h -- the few real /src code offsets the runtime hands
to the module inits (they store them where the asm stores them; nothing
in protected mode jumps to them), read from tools/asm86's symbol tables
so they follow the /src build instead of being copied by hand."""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
KERNEL = os.path.join(ROOT, 'src', 'kernel')
SYM_RE = re.compile(r'^\s*(\S+)\s+label\s+([0-9A-Fa-f]+)h', re.MULTILINE)

WANT = {
    'SUP.A86': [('user_retf', 'SUP_USER_RETF'), ('notick', 'SUP_NOTICK'),
                ('idle', 'SUP_IDLE'), ('user_entry', 'SUP_USER_ENTRY')],
    'RTM.A86': [('fdisp', 'RTM_FDISP'), ('farpdisp', 'RTM_FARPDISP')],
}


def symbols(src):
    out = subprocess.run([sys.executable, os.path.join(ROOT, 'tools', 'asm86.py'),
                          os.path.join(KERNEL, src), '-I', KERNEL, '--symbols'],
                         capture_output=True, text=True, check=True).stdout
    return {k.lower(): int(v, 16) for k, v in SYM_RE.findall(out)}


def main():
    lines = ['/* generated by rt/gen_syms.py from src/kernel -- do not edit */',
             '#ifndef RT_SYMS_H', '#define RT_SYMS_H']
    for src, names in WANT.items():
        sym = symbols(src)
        for name, macro in names:
            lines.append(f'#define {macro} 0x{sym[name]:04X} /* {src}: {name} */')
    lines.append('#endif')
    with open(sys.argv[1], 'w') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
