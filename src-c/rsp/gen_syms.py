#!/usr/bin/env python3
"""gen_syms.py OUT.h -- every label of each src/rsp/*.A86, as
<NAME>_<label> offsets (code or data segment, as the .A86 places it),
read from tools/asm86's symbol table. The C versions in src-c/rsp/
static-assert their data images' field offsets, and place their
code-segment constants, against these."""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RSP_DIR = os.path.join(ROOT, 'src', 'rsp')
SYM_RE = re.compile(r'^\s*(\S+)\s+label\s+([0-9A-Fa-f]+)h', re.MULTILINE)
NAMES = ['CLOCK', 'ECHO', 'TMP', 'SUBMIT', 'RANDOM']


def main():
    lines = ['/* generated by rsp/gen_syms.py from src/rsp -- do not edit */',
             '#ifndef RSP_SYMS_H', '#define RSP_SYMS_H']
    for name in NAMES:
        out = subprocess.run([sys.executable, os.path.join(ROOT, 'tools', 'asm86.py'),
                              os.path.join(RSP_DIR, name + '.A86'), '--symbols'],
                             capture_output=True, text=True, check=True).stdout
        for label, value in sorted(SYM_RE.findall(out), key=lambda kv: (int(kv[1], 16), kv[0])):
            macro = f'{name}_{label.upper()}'
            if not re.fullmatch(r'[A-Z0-9_]+', macro):
                continue
            lines.append(f'#define {macro} 0x{int(value, 16):04X}')
    lines.append('#endif')
    with open(sys.argv[1], 'w') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
